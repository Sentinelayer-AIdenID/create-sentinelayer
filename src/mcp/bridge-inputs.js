// bridge-inputs.js -- the inputs the MCP CLI bridge exposes, command by command.
//
// Default-deny. An input not listed for its command is not exposed; a command with no entry,
// or with an argument or a required option that is not listed, is not exposed at all. Commands
// the bridge blocks outright (src/mcp/cli-command-tools.js) need no entry. DENIED records each
// input deliberately left out, and why. A unit test walks the command tree and fails on any
// input of an exposed command that is in neither list, and on entries that name nothing.
//
// Nothing that names where a request goes (a URL, host, origin, endpoint or gateway) is allowed:
// a tool caller never chooses a destination for this machine's credentials. Those commands use
// the configured API and pocket gateway. Nor is anything that names a program to run (an
// executable, binary, shell, command or script) or turns off a safety check (a sandbox, approval
// or similar bypass): a tool caller never chooses what this machine executes, or how freely.

