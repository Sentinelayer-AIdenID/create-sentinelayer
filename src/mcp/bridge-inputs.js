/** The inputs a command exposes through the bridge, or null if it has no entry. */
export function bridgeAllowedInputs(commandPath) {
  const listed = BRIDGE_ALLOWED_INPUTS[commandPath];
  return typeof listed === "string" ? new Set(listed.split(/\s+/).filter(Boolean)) : null;
}
